"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const os=require("node:os");
const dir=fs.mkdtempSync(path.join(os.tmpdir(),"pig-race-test-"));
process.env.SCORE_FILE=path.join(dir,"scores.json");
const app=require("./server.cjs");
(async()=>{
 await new Promise(resolve=>app.listen(0,"127.0.0.1",resolve));
 const base="http://127.0.0.1:"+app.address().port;
 const score={matchId:"test-match-001",playerName:"Heo Master",pigName:"Cơ Bắp",mode:"math",rank:1,correct:3,fastest:2,finishTime:56.6};
 const one=await fetch(base+"/api/results",{method:"POST",headers:{"Content-Type":"application/json"},body:JSON.stringify(score)});
 assert.equal(one.status,201);
 const body=await one.json();assert.equal(body.points,140);assert.equal(body.saved,true);
 const dupe=await fetch(base+"/api/results",{method:"POST",headers:{"Content-Type":"application/json"},body:JSON.stringify(score)});
 assert.equal(dupe.status,200);
 assert.equal((await dupe.json()).duplicate,true);
 const top=await fetch(base+"/api/top10");
 assert.equal(top.status,200);
 const t=await top.json();assert.equal(t.players[0].name,"Heo Master");assert.equal(t.players[0].races,1);
 const list=await (await fetch(base+"/api/scores")).json();
 assert.equal(list.history.length,1);
 const onDisk=JSON.parse(fs.readFileSync(process.env.SCORE_FILE,"utf8"));
 assert.equal(onDisk.players[0].totalPoints,140);
 const config=await (await fetch(base+"/site/config.js")).text();
 assert.match(config,/PIG_SHARED_SCORE_API=true/);
 const page=await (await fetch(base+"/")).text();
 assert.match(page,/id="playerNameInput"/);
 const blocked=await fetch(base+"/server/server.cjs");
 assert.equal(blocked.status,404);
 console.log("File-backed score server tests passed: POST, idempotency, file, Top 10 and static pages.");
})().catch(e=>{console.error(e);process.exitCode=1}).finally(async()=>{await new Promise(resolve=>app.close(resolve));fs.rmSync(dir,{recursive:true,force:true});});
